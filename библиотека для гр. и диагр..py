"""Что за библиотека matplotlib.pyplot?
matplotlib — это самая популярная библиотека в Python для построения графиков и диаграмм (как в Excel, только кодом).
pyplot — это модуль внутри matplotlib, который позволяет рисовать графики простыми командами (как в программе MATLAB).
as plt — это просто сокращение. Чтобы каждый раз не писать matplotlib.pyplot.plot(), мы пишем коротко plt.plot().
Зачем нужна: Рисовать графики функций, столбчатые диаграммы, свечи на бирже, визуализировать данные."""