"""Что за методы на @ (Декораторы)
В Python значок @ над функцией — это декоратор. Это специальная «обертка», которая меняет поведение функции или метода.
В вашем коде используются три вида декораторов:
@property — превращает метод в атрибут. Теперь, чтобы получить значение, не нужно писать скобки ().
python
# Без @property:  student.get_age()
# С @property:    student.age
@age.setter — позволяет безопасно изменять значение через @property. Если вы напишете student.age = -5, сработает этот метод, и он проверит данные (например, выбросит ошибку, если возраст не число).
@staticmethod и @classmethod (о которых мы говорили ранее) — также являются декораторами."""