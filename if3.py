n = int(input('Введите возраст: '))
if 0 < n < 18:
    print('Вы несовершеннолетний')
elif 0 == n:
    print('Вы младенец')
elif 18 <= n < 70:
        print('Вы взрослый')
elif n >= 70 and n < 100:
        print('Вы пожилой')
elif 100 <= n < 120:
        print('Долгожитель')
elif 120 <= n:
        print('Вы гиганская черепаха')
else:
    print('Вы ввели не число')
